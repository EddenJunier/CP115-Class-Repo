#average score calculation
score1 = float(input("Enter the first score: "))
score2 = float(input("Enter the second score: "))
score3 = float(input("Enter the third score: "))
average_score = (score1 + score2 + score3) / 3

print(f"\nThe first score is: {score1}")
print(f"The second score is: {score2}")
print(f"The third score is: {score3}")
print(f"\nThe total score is: {score1 + score2 + score3}")
print(f"\nThe average score is: {average_score:.2f}")
